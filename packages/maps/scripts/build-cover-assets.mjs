/** Packaging only: retain generated pixels and dimensions, encode for the offline preview. */
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import sharp from 'sharp';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const collection=process.argv[2]||'v3.3';
if(!['v3.2','v3.3'].includes(collection))throw Error('Unsupported cover collection');
const names={focus:'Фокус',research:'Исследование',launch:'Запуск',design:'Дизайн',development:'Разработка',planning:'Планирование'};
const assets=[],manifest=[];
for(const [id,name] of Object.entries(names)){
  const source=await readFile(path.join(root,'assets/covers-'+collection,id+'.png'));
  const {data,info}=await sharp(source).webp({quality:88,effort:6}).toBuffer({resolveWithObject:true});
  await writeFile(path.join(root,'assets/covers-'+collection,id+'.webp'),data);
  assets.push({id,name,src:'data:image/webp;base64,'+data.toString('base64')});
  manifest.push({id,name,width:info.width,height:info.height,bytes:data.length,sha256:createHash('sha256').update(data).digest('hex'),sourceSha256:createHash('sha256').update(source).digest('hex')});
}
await writeFile(path.join(root,'src/board/cover-assets.js'),'// Generated by scripts/build-cover-assets.mjs from the six imagegen originals.\nexport const COVER_PRESETS='+JSON.stringify(assets)+';\n');
await writeFile(path.join(root,'assets/covers-'+collection,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify(manifest,null,2));
